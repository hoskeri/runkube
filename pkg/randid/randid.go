// Package randid derives stable, non-secret identifiers from a seed: MAC
// addresses, IPv4/IPv6 addresses, ULA prefixes, byte sequences and hex
// strings. The same seed always yields the same values, so identities are
// predictable across restarts without being hardcoded (docs/TODO.md,
// "Dynamic network interface"). Seeds are typically machine ids, node names
// or object ids.
//
// A seed that is exactly 16 bytes (32 hexadecimal characters) is interpreted
// as raw bytes, so identities stay readable for machine-id-style seeds; any
// other seed is hashed (SHA-256). Every generator derives from those 16
// bytes, so values derived from the same seed are coherent by construction.
//
// # Security considerations
//
// randid is deterministic and NOT secret. Every value is a plain function of
// the seed: anyone who knows the seed can recompute — and for 32-hex-char
// seeds the identity bytes ARE the seed, so the derived bytes are directly
// readable. Do NOT use randid for credentials, secrets, passwords, API keys,
// bearer or CSRF tokens, nonces, session ids, or any value that must be
// unpredictable or unguessable. Those need a cryptographic random source,
// e.g. crypto/rand. randid exists so emulated identities are stable and
// predictable (so they can be stated in config, kubeconfigs and tests), never
// so they can be kept secret. There is deliberately no alphanumeric "token"
// generator.
package randid

import (
	"crypto/sha256"
	"encoding/hex"
	"net"
	"net/netip"
)

// seedBytes returns the 16-byte identity for a seed: the seed itself when it
// is 16 bytes (32 hex characters), otherwise a SHA-256 digest truncated to 16
// bytes. All public generators derive from these bytes.
func seedBytes(seed string) [16]byte {
	var b [16]byte
	if len(seed) == 2*16 {
		if raw, err := hex.DecodeString(seed); err == nil {
			copy(b[:], raw)
			return b
		}
	}
	h := sha256.Sum256([]byte(seed))
	copy(b[:], h[:16])
	return b
}

// Bytes returns n deterministic bytes for a seed. The first 16 bytes are the
// seed's identity bytes (see the package comment); longer outputs are
// generated by hashing the identity together with a block counter. Bytes is
// the general primitive the other generators are built on.
func Bytes(seed string, n int) []byte {
	if n <= 0 {
		return nil
	}
	base := seedBytes(seed)
	if n <= len(base) {
		return append([]byte(nil), base[:n]...)
	}
	out := append([]byte(nil), base[:]...)
	for len(out) < n {
		h := sha256.New()
		h.Write(base[:])
		h.Write([]byte{byte(len(out)), byte(len(out) >> 8)})
		out = append(out, h.Sum(nil)...)
	}
	return out[:n]
}

// MAC returns a 6-byte interface address derived from seed: unicast (bit 0
// clear) and locally administered (bit 1 set), so it can never collide with a
// real vendor OUI.
func MAC(seed string) net.HardwareAddr {
	b := seedBytes(seed)
	mac := make(net.HardwareAddr, 6)
	copy(mac, b[:6])
	mac[0] = mac[0]&0xfe | 0x02
	return mac
}

// IPv4 returns a private 10/8 address derived from seed:
// 10.<b12>.<b13>.<b14> from the identity bytes.
func IPv4(seed string) net.IP {
	b := seedBytes(seed)
	return net.IPv4(10, b[12], b[13], b[14])
}

// IPv6 returns a ULA (fd00::/8) interface address derived from seed: the
// first 14 identity bytes under the fd00::/8 prefix.
func IPv6(seed string) net.IP {
	b := seedBytes(seed)
	ip6 := make(net.IP, net.IPv6len)
	ip6[0], ip6[1] = 0xfd, 0x00
	copy(ip6[2:], b[:14])
	return ip6
}

// ULA returns an RFC 4193 unique-local prefix derived from seed: the
// identity's first 5 bytes form the 40-bit global ID and the next 2 bytes the
// 16-bit subnet ID, under fd + /64. It is the layout used for service address
// ranges (pkg/config generates the same shape).
func ULA(seed string) netip.Prefix {
	b := seedBytes(seed)
	var addr [16]byte
	addr[0] = 0xfd
	copy(addr[1:6], b[:5])  // 40-bit global ID
	copy(addr[6:8], b[5:7]) // 16-bit subnet ID
	return netip.PrefixFrom(netip.AddrFrom16(addr), 64)
}

// Hex returns n lowercase hexadecimal characters derived from seed, suitable
// for deterministic suffixes and identifiers. It is the hexadecimal encoding
// of Bytes(seed, ceil(n/2)); for a 32-hex seed and n = 32 the result is the
// seed itself.
func Hex(seed string, n int) string {
	if n <= 0 {
		return ""
	}
	return hex.EncodeToString(Bytes(seed, (n+1)/2))[:n]
}
